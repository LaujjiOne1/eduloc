/** Vrai pour une valeur de la forme CODE_EN_MAJUSCULES (code d'erreur métier). */
export const isErrorCode = (value: unknown): value is string =>
  typeof value === 'string' && /^[A-Z][A-Z0-9]*(?:_[A-Z0-9]+)*$/.test(value);
